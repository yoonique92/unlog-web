import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";

const root = process.cwd();
const stage = await mkdtemp(join(root, ".pages-build-"));
const basePath = "/unlog-web";
const routes = ["compatibility", "onboarding/saju", "result", "saju", "saju/detail", "today"];
const unavailable = {
  charge: ["로그 상점", "운석 충전과 사용에는 계정 연결이 필요해요."],
  friends: ["로그 프렌즈", "친구를 초대하고 정원을 꾸미려면 계정 연결이 필요해요."],
  "saju/yearly": ["신년운세", "신년운세를 보려면 계정에 내 사주를 연결해야 해요."],
};

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = await Promise.all(entries.map((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesIn(path) : [path];
  }));
  return paths.flat();
}

async function edit(path, transform) {
  const fullPath = join(stage, path);
  await writeFile(fullPath, transform(await readFile(fullPath, "utf8")));
}

try {
  await mkdir(join(stage, "app"));
  for (const file of ["favicon.ico", "globals.css", "layout.tsx", "page.tsx"]) {
    await cp(join(root, "app", file), join(stage, "app", file));
  }
  for (const route of routes) {
    const directory = join(stage, "app", route);
    await mkdir(directory, { recursive: true });
    await cp(join(root, "app", route, "page.tsx"), join(directory, "page.tsx"));
  }
  for (const [route, [title, description]] of Object.entries(unavailable)) {
    const directory = join(stage, "app", route);
    await mkdir(directory, { recursive: true });
    await writeFile(join(directory, "page.tsx"), `
import Link from "next/link";
export default function ServerFeature() {
  return (
    <main className="space-y-4 p-6">
      <h1 className="text-xl font-bold">${title}</h1>
      <p>${description}</p>
      <Link className="underline" href="/">오늘의 운세 보러 가기</Link>
    </main>
  );
}
`);
  }
  await mkdir(join(stage, "app", "my"));
  await writeFile(join(stage, "app", "my", "page.tsx"), `
import Link from "next/link";
export default function LocalProfilePage() {
  return (
    <main className="space-y-4 p-6">
      <h1 className="text-xl font-bold">내 사주</h1>
      <p>입력한 정보는 이 브라우저에 저장돼요.</p>
      <Link className="underline" href="/onboarding/saju">내 사주 정보 입력</Link>
    </main>
  );
}
`);
  for (const entry of ["components", "lib", "public", "package.json", "postcss.config.mjs", "tsconfig.json"]) {
    await cp(join(root, entry), join(stage, entry), {
      recursive: true,
      filter: (path) => !/\.test\.[cm]?[jt]sx?$/.test(path),
    });
  }
  await edit("app/layout.tsx", (source) => source
    .replace(/^import .*"next\/font\/google";\r?\n/m, "")
    .replace(/const geistSans = [\s\S]*?(?=export const metadata)/, "")
    .replace(/className=\{[^\n]+\}/, 'className="h-full antialiased"')
    .replace("Create Next App", "운로그")
    .replace("Generated by create next app", "오늘의 운세와 사주, 궁합"));
  for (const directory of ["app", "components", "lib"]) {
    for (const file of await filesIn(join(stage, directory))) {
      if (!/\.(css|tsx?)$/.test(file)) continue;
      const source = await readFile(file, "utf8");
      const updated = source.replace(/(["'`(])\/(image|font)\//g, `$1${basePath}/$2/`);
      if (updated !== source) await writeFile(file, updated);
    }
  }
  await writeFile(join(stage, "next.config.mjs"), `
export default {
  output: "export",
  basePath: ${JSON.stringify(basePath)},
  trailingSlash: true,
  images: { unoptimized: true },
  typescript: { ignoreBuildErrors: false },
};`);
  const result = spawnSync(process.execPath, [
    resolve(root, "node_modules/next/dist/bin/next"), "build", "--webpack",
  ], {
    cwd: stage,
    stdio: "inherit",
    env: {
      ...process.env,
      NEXT_PUBLIC_UNLOG_PAGES: "true",
      NEXT_PUBLIC_UNLOG_STRENGTH_D_PRODUCTION_V1: "true",
    },
  });
  if (result.status !== 0) throw result.error ?? new Error("Pages build failed.");
  const exported = join(stage, "out");
  for (const route of ["", "my", ...routes, ...Object.keys(unavailable)]) {
    const html = await readFile(join(exported, route, "index.html"), "utf8");
    if (!html.includes(`src="${basePath}/_next/`)) {
      throw new Error(`Missing Pages script prefix on /${route}`);
    }
  }
  await writeFile(join(exported, ".nojekyll"), "");
  const output = join(root, "out");
  await rm(output, { recursive: true, force: true });
  await cp(exported, output, { recursive: true });
} finally {
  await rm(stage, { recursive: true, force: true });
}
