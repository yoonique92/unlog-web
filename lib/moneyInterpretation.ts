type MoneyInput = {
  counts: Record<string, number>;
};

export function getMoneyInterpretation({ counts }: MoneyInput) {
  const bijeop =
    (counts["비견"] || 0) + (counts["겁재"] || 0);

  const siksang =
    (counts["식신"] || 0) + (counts["상관"] || 0);

  const jaeseong =
    (counts["편재"] || 0) + (counts["정재"] || 0);

  const gwanseong =
    (counts["편관"] || 0) + (counts["정관"] || 0);

  const inseong =
    (counts["편인"] || 0) + (counts["정인"] || 0);

  let title = "";
  let summary = "";
  let strength = "";
  let caution = "";
  let management = "";
  let keywords: string[] = [];

  if (jaeseong >= 2) {
    title = "현실적인 성과와 수익을 중요하게 보는 타입";

    summary =
      "돈이나 성과처럼 눈에 보이는 결과에 대한 감각이 비교적 분명한 편이에요.";

    strength =
      "목표를 현실적인 숫자와 결과로 연결하는 힘이 있고, 자원이나 기회를 활용하는 감각이 살아날 수 있어요.";

    caution =
      "성과를 너무 빠르게 확인하려고 하면 단기적인 선택에 마음이 흔들릴 수 있어요.";

    management =
      "매달 들어오고 나가는 돈을 직접 확인하고, 구체적인 목표를 정해서 관리하는 방식이 잘 맞을 수 있어요.";

    keywords = [
      "현실 감각",
      "성과",
      "수익 구조",
      "자원 관리",
      "목표 설정",
    ];
  } else if (siksang >= 2 && jaeseong === 0) {
    title = "실력과 결과물을 수익으로 연결하는 타입";

    summary =
      "돈 자체를 직접 좇기보다 자신이 잘하는 일이나 만들어낸 결과물을 통해 수익을 만드는 방식이 더 자연스러울 수 있어요.";

    strength =
      "기술, 경험, 콘텐츠, 전문성처럼 자신이 만들어낸 가치를 오래 쌓을수록 수익 구조가 탄탄해질 가능성이 있어요.";

    caution =
      "잘하는 것과 돈이 되는 것은 별개의 문제일 수 있어요. 가격, 계약, 수익 구조를 의식적으로 설계하는 연습이 중요해요.";

    management =
      "단기적인 수익 변화에 흔들리기보다 전문성과 결과물을 꾸준히 쌓으면서 장기적인 수입 기반을 만드는 방식이 잘 맞을 수 있어요.";

    keywords = [
      "전문성",
      "결과물",
      "장기 축적",
      "독립 수익",
      "콘텐츠",
      "기술",
    ];
  } else if (bijeop >= 2 && jaeseong <= 1) {
    title = "내가 직접 계획할 때 돈 관리가 편해지는 타입";

    summary =
      "타인의 기준에 맞춰 움직이기보다 스스로 결정할 수 있을 때 금전적인 판단도 더 편해질 수 있어요.";

    strength =
      "독립적인 판단과 실행력이 강점이 될 수 있고, 자신만의 방식으로 수익 구조를 만들려는 힘이 있어요.";

    caution =
      "확신이 강해질수록 혼자 결정하거나 주변의 조언을 놓칠 수 있어요. 큰 금액일수록 객관적인 기준을 함께 두는 것이 좋아요.";

    management =
      "내가 통제할 수 있는 예산과 목표를 분명히 정하고, 큰 지출이나 투자는 한 번 더 검토하는 방식이 도움이 돼요.";

    keywords = [
      "독립성",
      "자기 주도",
      "예산 관리",
      "장기 계획",
      "신중한 결정",
    ];
  } else if (inseong >= 2) {
    title = "지식과 전문성을 자산으로 쌓는 타입";

    summary =
      "빠르게 돈을 늘리기보다 배우고 익힌 것을 자산으로 축적하는 방식에 더 익숙할 수 있어요.";

    strength =
      "공부, 정보, 전문성, 자격과 경험처럼 시간이 지나도 남는 자산을 만드는 데 강점이 있을 수 있어요.";

    caution =
      "준비와 공부에만 머무르면 실제 수익으로 연결되는 시점이 늦어질 수 있어요.";

    management =
      "배운 것을 서비스나 결과물로 연결하는 작은 시도를 반복하면 수익 구조를 만들기 쉬워질 수 있어요.";

    keywords = [
      "전문 지식",
      "학습",
      "정보",
      "장기 자산",
      "전문성",
    ];
  } else if (gwanseong >= 2) {
    title = "안정적인 구조 안에서 자산을 쌓는 타입";

    summary =
      "예측 가능한 소득과 안정적인 구조를 중요하게 여기는 편일 수 있어요.";

    strength =
      "규칙적인 수입과 계획적인 관리에 강점이 있고, 장기적으로 자산을 쌓는 방식과 잘 맞을 수 있어요.";

    caution =
      "안정성을 너무 중요하게 생각하면 새로운 수익 기회를 지나치게 조심스럽게 바라볼 수 있어요.";

    management =
      "안정적인 기반을 유지하면서 일부 자원을 새로운 기회에 배분하는 방식이 균형을 잡는 데 도움이 돼요.";

    keywords = [
      "안정성",
      "계획",
      "장기 저축",
      "정기 수입",
      "위험 관리",
    ];
  } else {
    title = "한 가지 방식보다 균형이 중요한 타입";

    summary =
      "특정한 금전 성향 하나가 강하게 드러나기보다 상황에 따라 여러 방식을 활용하는 편일 수 있어요.";

    strength =
      "한 가지 방식에 갇히지 않고 상황에 맞게 돈을 벌고 관리하는 방식을 조정할 수 있어요.";

    caution =
      "기준이 자주 바뀌면 금전 관리가 느슨해질 수 있으니 기본적인 원칙을 정해두는 것이 좋아요.";

    management =
      "고정 지출, 저축, 여유 자금처럼 기본 구조를 먼저 만들고 그 위에서 유연하게 움직이는 방식이 좋아요.";

    keywords = [
      "균형",
      "기본 원칙",
      "예산",
      "유연성",
      "장기 관리",
    ];
  }

  return {
    title,
    summary,
    strength,
    caution,
    management,
    keywords,
  };
}
