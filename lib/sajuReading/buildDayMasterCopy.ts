export function buildDayMasterCopy(
  facts: SajuReadingFacts,
): SajuReadingSectionCopy {
  const seed = DAY_MASTER_COPY[facts.dayMaster.stem];
  if (!seed) throw new Error(`Missing day-master copy for ${facts.dayMaster.stem}`);

  return {
    headline: seed.headline,
    paragraphs: [
      `${seed.sentences[0]} ${seed.sentences[1]} ${seed.sentences[2]}`,
      `다만 일간 하나만으로 사람의 성격을 모두 설명할 수는 없습니다. 실제 모습은 오행의 분포와 십성 구성이 함께 작용하면서 달라질 수 있어요. 여기서는 ${facts.dayMaster.koreanName}을 판단과 행동이 시작되는 기본 방향으로 보는 편이 좋습니다.`,
    ],
    sourceFacts: [
      `dayMaster=${facts.dayMaster.stem}(${facts.dayMaster.koreanName})`,
      `element=${facts.dayMaster.element}`,
      `yinYang=${facts.dayMaster.yinYang}`,
    ],
  };
}
