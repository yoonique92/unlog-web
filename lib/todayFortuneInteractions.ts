function pick<T>(items: T[], seed: number): T {
  return items[Math.abs(seed) % items.length];
}

export function getTenGodInteraction(
  stemTenGod: TenGodName,
  branchTenGod: TenGodName,
  seed: number
) {
  const key = `${stemTenGod}-${branchTenGod}`;

  const interaction = interactions[key];

  if (!interaction) {
    return null;
  }

  return {
    headline: pick(
      interaction.headline,
      seed
    ),

    tip: pick(
      interaction.tip,
      seed + 1
    ),

    love: interaction.love
      ? pick(interaction.love, seed + 2)
      : null,

    money: interaction.money
      ? pick(interaction.money, seed + 3)
      : null,

    career: interaction.career
      ? pick(interaction.career, seed + 4)
      : null,

    study: interaction.study
      ? pick(interaction.study, seed + 5)
      : null,

    health: interaction.health
      ? pick(interaction.health, seed + 6)
      : null,
  };
}
