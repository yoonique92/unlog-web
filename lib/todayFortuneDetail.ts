function getHealthDetail(
  stem: TenGodName,
  branch: TenGodName,
  strength: string,
  score: number
) {
  const stemGroup =
    getTenGodGroup(stem);

  const tone =
    getScoreTone(score);

  const isStrong =
    strength.includes("강");

  const isWeak =
    strength.includes("약");

  if (tone === "high") {
    if (isWeak) {
      return "오늘은 컨디션이 비교적 안정적으로 이어져 평소보다 몸의 리듬을 편안하게 유지할 수 있는 날이에요. 다만 평소 쉽게 지치는 편이라면 좋은 컨디션을 한꺼번에 소진하지 않는 것이 중요합니다. 지금 상태를 오래 유지할 수 있도록 활동 사이에 여유를 챙겨두면 좋습니다.";
    }

      return "몸이 비교적 가볍게 느껴져 미뤄두었던 일이나 가벼운 운동을 시작하기에 부담이 적을 수 있어요. 처음부터 무리하게 양을 늘리기보다, 움직인 만큼 쉬어야 지금의 컨디션을 오래 유지할 수 있습니다.";
  }

  if (tone === "low") {
    return "일정이 많으면 생각보다 체력이 빨리 떨어지고 피로도 오래 남을 수 있어요. 몸이 보내는 신호를 뒤늦게 알아차리지 않도록, 모든 일을 끝낸 뒤가 아니라 일정 사이에 짧은 휴식을 넣어두는 편이 좋습니다.";
  }

  if (stemGroup === "responsibility") {
    return "오늘은 해야 할 일에 집중하다 보면 피로를 늦게 알아차릴 수 있는 날이에요. 긴장된 상태가 오래 이어지면 몸보다 마음이 먼저 지칠 수 있어 일정 중간에 쉬는 시간이 필요합니다. 해야 할 일을 모두 끝낸 뒤 쉬려고 하지 말고 중간중간 짧게라도 휴식을 넣어보세요.";
  }

  if (stemGroup === "expression") {
    return "오늘은 생각과 활동량이 함께 늘어나 체력을 빠르게 쓸 수 있는 날이에요. 컨디션이 좋다고 느껴져도 계속 움직이면 오후나 저녁에 피로가 한꺼번에 몰릴 수 있습니다. 활동 사이에 잠깐씩 몸을 풀고 물을 챙겨 마셔보세요.";
  }

  if (isWeak) {
    return "오늘은 체력을 끌어올리기보다 가진 힘을 무리 없이 나누는 것이 더 중요한 날이에요. 일정을 빽빽하게 채우면 집중력과 컨디션이 함께 떨어질 수 있습니다. 꼭 필요한 일에 힘을 집중하고 나머지는 여유 있게 조절해보세요.";
  }

  if (isStrong) {
    return "오늘은 평소보다 활동할 힘이 충분하게 느껴질 수 있는 날이에요. 다만 힘이 남아 있다고 한 번에 모두 쓰면 뒤로 갈수록 피로가 크게 느껴질 수 있습니다. 움직인 만큼 휴식도 함께 챙기면서 하루의 속도를 조절해보세요.";
  }

  return "평소 먹고 자는 시간을 크게 바꾸지 않을수록 몸이 편하게 느껴질 수 있어요. 갑자기 일정을 늘리기보다 익숙한 생활 리듬을 지키면 컨디션도 덜 흔들립니다. 틈이 날 때 짧게 쉬어두는 것만으로도 충분해요.";
}

