type TenGodGroup =
  | "self"
  | "expression"
  | "wealth"
  | "responsibility"
  | "resource";

type ScoreTone =
  | "high"
  | "mid"
  | "low";

/*
  십성을 5개의 큰 성향으로 묶습니다.
*/
function getTenGodGroup(
  tenGod: TenGodName
): TenGodGroup {
  if (
    tenGod === "비견" ||
    tenGod === "겁재"
  ) {
    return "self";
  }

  if (
    tenGod === "식신" ||
    tenGod === "상관"
  ) {
    return "expression";
  }

  if (
    tenGod === "편재" ||
    tenGod === "정재"
  ) {
    return "wealth";
  }

  if (
    tenGod === "편관" ||
    tenGod === "정관"
  ) {
    return "responsibility";
  }

  return "resource";
}

/*
  분야별 점수를 세 구간으로 나눕니다.

  high : 80점 이상
  mid  : 65 ~ 79점
  low  : 64점 이하
*/
function getScoreTone(
  score: number
): ScoreTone {
  if (score >= 80) {
    return "high";
  }

  if (score >= 65) {
    return "mid";
  }

  return "low";
}
function removeTodayPrefix(
  text: string
) {
  return text.replace(
    /^오늘은\s*/,
    ""
  );
}
