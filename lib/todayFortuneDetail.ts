function getPeopleDetail(
  stem: TenGodName,
  branch: TenGodName,
  score: number
) {
  const stemGroup =
    getTenGodGroup(stem);

  const tone =
    getScoreTone(score);

  if (tone === "high") {
    if (
      stemGroup === "wealth" ||
      stemGroup === "expression"
    ) {
      return "가볍게 나눈 이야기에서 생각하지 못한 공통점이나 도움이 되는 정보를 발견할 수 있어요. 많은 사람을 만나려고 애쓰기보다 마음이 편한 사람과 대화를 조금 더 이어가면, 필요한 인연도 자연스럽게 구분됩니다.";
    }

    return "오늘은 주변 사람들과의 관계가 비교적 편안하게 이어지고 신뢰를 쌓기 좋은 날이에요. 평소보다 상대의 이야기를 자연스럽게 받아들일 수 있어 작은 대화에서도 관계가 한층 가까워질 가능성이 있습니다. 먼저 다가가기 어렵다면 가벼운 안부나 짧은 대화부터 시작해도 좋습니다.";
  }

  if (tone === "low") {
    if (stemGroup === "self") {
      return "오늘은 자신의 의견과 기준이 강해져 사람들과의 작은 차이도 크게 느껴질 수 있는 날이에요. 상대가 나와 다르게 행동하면 답답하게 느껴져 필요 이상의 거리감이 생길 가능성도 있습니다. 내 생각을 설명한 뒤에는 상대의 입장도 충분히 들을 시간을 가져보세요.";
    }

    return "상대가 무심코 한 말도 평소보다 오래 마음에 남을 수 있어요. 별다른 의도가 없는 표현까지 크게 받아들이면 관계가 불필요하게 복잡해질 수 있습니다. 바로 판단하기보다 어떤 뜻이었는지 차분하게 확인해두면 좋습니다.";
  }

  if (
    stemGroup === "wealth" ||
    stemGroup === "expression"
  ) {
    return "평소에는 흘려들었던 이야기에서 지금 필요한 정보나 새로운 방법을 알게 될 수 있어요. 사람을 많이 만나기보다 편안하게 대화를 이어가면, 누구와 이야기를 더 나눌지도 자연스럽게 보일 수 있습니다.";
  }

  if (
    stemGroup === "responsibility" ||
    stemGroup === "resource"
  ) {
    return "오늘은 새로운 관계를 넓히기보다 이미 알고 지내는 사람들과 신뢰를 쌓는 데 더 의미가 있는 날이에요. 상대의 말을 충분히 듣고 약속이나 기본적인 예의를 지키는 모습이 좋은 인상으로 남을 수 있습니다. 관계를 서두르기보다 지금 이어지고 있는 인연을 조금 더 정성스럽게 살펴보는 편이 좋습니다.";
  }

  return "오늘은 사람들과 함께 있을 때도 자신의 생각과 기준이 분명하게 드러날 수 있는 날이에요. 상대가 나와 다른 방식으로 행동하면 답답하게 느껴질 수 있지만 꼭 어느 한쪽이 틀린 것은 아닐 수 있습니다. 내 의견을 분명하게 전하되 상대의 방식을 인정할 수 있는 부분도 찾아보세요.";
}

