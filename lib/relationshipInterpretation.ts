type RelationshipInput = {
  counts: Record<string, number>;
};

export function getRelationshipInterpretation({
  counts,
}: RelationshipInput) {
  const bijeop =
    (counts["비견"] || 0) + (counts["겁재"] || 0);

  const siksang =
    (counts["식신"] || 0) + (counts["상관"] || 0);

  const jaeseong =
    (counts["편재"] || 0) + (counts["정재"] || 0);

  const gwanseong =
    (counts["편관"] || 0) + (counts["정관"] || 0);

  const inseong =
    (counts["편인"] || 0) + (counts["정인"] || 0);

  let title = "";
  let summary = "";
  let strength = "";
  let caution = "";
  let advice = "";
  let keywords: string[] = [];

  if (bijeop >= 2 && siksang >= 2) {
    title = "가까워져도 나다움을 지키고 싶은 타입";

    summary =
      "사람과 가까워지는 것을 싫어하지는 않지만, 관계 안에서도 자신의 기준과 생활 리듬을 중요하게 생각하는 편이에요.";

    strength =
      "상대에게 모두 맞추기보다 서로 각자의 영역을 존중하는 관계를 만들 수 있어요. 편안해지면 솔직하고 자연스러운 매력도 잘 드러나는 편이에요.";

    caution =
      "혼자 생각을 정리한 뒤 결론을 내리는 습관이 강하면 상대는 자신의 의견이 충분히 반영되지 않았다고 느낄 수 있어요.";

    advice =
      "상대가 알아서 이해해주기를 기다리기보다, 내 생각과 감정을 중간중간 말로 공유하는 것이 관계를 훨씬 편안하게 만들어줘요.";

    keywords = [
      "독립성",
      "솔직함",
      "자기 기준",
      "편안함",
      "대화",
    ];
  } else if (bijeop >= 2) {
    title = "신뢰가 쌓여야 마음을 여는 타입";

    summary =
      "관계에서도 자신의 기준이 분명해서, 처음부터 빠르게 가까워지기보다 상대를 충분히 지켜본 뒤 마음을 여는 편일 수 있어요.";

    strength =
      "한번 신뢰한 사람에게는 쉽게 흔들리지 않고 꾸준하게 관계를 이어가는 힘이 있어요.";

    caution =
      "상대에게 기대기보다 혼자 해결하려는 성향이 강하면, 가까운 사람도 내가 무엇을 원하는지 알기 어려울 수 있어요.";

    advice =
      "도움을 받는 것을 약함으로 생각하지 말고, 작은 일부터 상대에게 부탁하거나 기대보는 연습이 도움이 돼요.";

    keywords = [
      "신뢰",
      "독립성",
      "꾸준함",
      "자기 기준",
      "거리 조절",
    ];
  } else if (siksang >= 2) {
    title = "표현과 대화가 관계의 온도를 만드는 타입";

    summary =
      "좋아하는 사람과 생각이나 취향을 나누고, 함께 재미있는 경험을 만드는 과정에서 관계가 깊어지는 편이에요.";

    strength =
      "말과 행동으로 애정을 표현하는 힘이 있고, 관계 안에서 분위기를 부드럽게 만들 수 있어요.";

    caution =
      "감정이 올라왔을 때 표현이 너무 빠르거나 직설적이면 상대에게 강하게 느껴질 수 있어요.";

    advice =
      "내가 하고 싶은 말을 바로 꺼내기 전에 상대가 어떻게 받아들일지를 한 번 생각하면 관계가 더 편안해질 수 있어요.";

    keywords = [
      "대화",
      "표현",
      "공감",
      "즐거움",
      "취향 공유",
    ];
  } else if (jaeseong >= 2) {
    title = "함께 현실을 만들어가는 관계를 중요하게 보는 타입";

    summary =
      "감정적인 끌림뿐 아니라 생활 방식이나 가치관처럼 현실적인 부분이 잘 맞는지도 중요하게 생각하는 편이에요.";

    strength =
      "관계를 책임감 있게 바라보고, 서로의 생활과 미래를 함께 계획하는 힘이 있어요.";

    caution =
      "관계를 지나치게 현실적인 기준으로만 판단하면 감정적인 교류가 부족해질 수 있어요.";

    advice =
      "효율이나 조건만큼 함께 있을 때 느끼는 편안함과 즐거움도 중요한 기준으로 두는 것이 좋아요.";

    keywords = [
      "현실성",
      "안정감",
      "생활",
      "책임감",
      "미래 계획",
    ];
  } else if (gwanseong >= 2) {
    title = "신뢰와 책임을 중요하게 생각하는 타입";

    summary =
      "관계에서도 약속과 책임을 중요하게 여기고, 상대가 믿을 수 있는 사람인지 살펴보는 편이에요.";

    strength =
      "관계를 가볍게 소비하기보다 오래 유지하려는 태도가 있고, 상대에게 안정감을 줄 수 있어요.";

    caution =
      "좋은 관계에 대한 기준이 높아지면 상대의 작은 실수에도 실망이 커질 수 있어요.";

    advice =
      "완벽한 관계를 만들기보다 서로의 부족한 부분을 조정해가는 과정도 관계의 일부라고 생각하면 좋아요.";

    keywords = [
      "신뢰",
      "책임감",
      "약속",
      "안정",
      "기준",
    ];
  } else if (inseong >= 2) {
    title = "마음이 통한다는 느낌이 중요한 타입";

    summary =
      "겉으로 보이는 조건보다 생각과 감정을 깊이 이해해주는 사람에게 마음이 움직이는 편일 수 있어요.";

    strength =
      "상대의 말과 감정을 세심하게 살피고, 관계를 깊이 이해하려는 힘이 있어요.";

    caution =
      "상대의 말과 행동에 의미를 너무 많이 부여하면 혼자 생각이 복잡해질 수 있어요.";

    advice =
      "추측으로 결론을 내리기보다 궁금한 것은 직접 물어보는 습관이 관계를 더 편하게 만들어줘요.";

    keywords = [
      "공감",
      "이해",
      "깊은 대화",
      "세심함",
      "정서적 연결",
    ];
  } else {
    title = "상황에 따라 관계의 방식을 조절하는 타입";

    summary =
      "한 가지 관계 방식이 강하게 드러나기보다 상대와 상황에 맞춰 여러 모습을 보여줄 수 있어요.";

    strength =
      "다양한 성향의 사람과 관계를 맺을 수 있고, 상황에 따라 유연하게 대응할 수 있어요.";

    caution =
      "상대에게 맞추는 데 집중하다 보면 정작 내가 원하는 관계의 모습이 무엇인지 놓칠 수 있어요.";

    advice =
      "관계를 시작할 때 내가 중요하게 생각하는 기준을 미리 정리해두면 선택이 훨씬 편해질 수 있어요.";

    keywords = [
      "유연성",
      "조율",
      "대화",
      "균형",
      "자기 이해",
    ];
  }

  return {
    title,
    summary,
    strength,
    caution,
    advice,
    keywords,
  };
}
